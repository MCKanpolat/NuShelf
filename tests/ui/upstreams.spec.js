import {test,expect} from '@playwright/test';
test('administrator manages upstream sources, routing, secrets references and cache',async({page,request})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/manage');
  await page.getByLabel('API key',{exact:true}).fill('test-only-admin-key-at-least-32-characters');
  await page.getByRole('button',{name:'Open workspace'}).click();
  await page.getByRole('link',{name:'Upstream sources',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Upstream sources',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Add nuget.org'}).click();
  await expect(page.getByLabel('NuGet V3 service index URL')).toHaveValue('https://api.nuget.org/v3/index.json');
  await page.getByLabel('Upstream authentication',{exact:true}).selectOption('bearer');
  await expect(page.getByLabel('Private source',{exact:true})).toBeChecked();
  await page.getByLabel('Upstream authentication',{exact:true}).selectOption('none');
  await page.getByLabel('Private source',{exact:true}).uncheck();
  const name=`UI source ${Date.now()}`;
  await page.getByLabel('Source name',{exact:true}).fill(name);
  await page.getByLabel('NuGet V3 service index URL').fill('http://registry:5000/v3/index.json');
  await page.getByLabel('Allow HTTP (development)',{exact:true}).check();
  await page.getByLabel('Allow private network endpoints',{exact:true}).check();
  await page.getByLabel('Include patterns',{exact:true}).fill('UiOnly.*');
  await page.getByRole('button',{name:'Test connection',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Connection succeeded.'})).toBeVisible();
  await page.getByLabel('NuGet V3 service index URL').fill('http://proxy-origin:8080/v3/index.json');
  await page.getByRole('button',{name:'Add source',exact:false}).click();
  const row=page.getByRole('row').filter({hasText:name});await expect(row).toBeVisible();
  await row.getByRole('button',{name:'Edit',exact:true}).click();
  await page.getByLabel('Priority',{exact:true}).fill('50');
  await page.getByLabel('Enabled',{exact:true}).uncheck();
  await page.getByRole('button',{name:'Save source'}).click();
  await expect(page.getByRole('row').filter({hasText:name})).toContainText('Disabled');
  await expect(page.locator('#toast')).toBeHidden({timeout:6000});
  await page.screenshot({path:'/results/upstream-sources.png',fullPage:true});
  await page.getByRole('link',{name:'Package cache',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Cached package archives',exact:true})).toBeVisible();
  await page.screenshot({path:'/results/upstream-cache.png',fullPage:true});
  await page.getByRole('link',{name:'Upstream sources',exact:true}).click();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('row').filter({hasText:name}).getByRole('button',{name:'Remove',exact:true}).click();
  await expect(page.getByRole('row').filter({hasText:name})).toHaveCount(0);
  expect(errors).toEqual([]);
});
